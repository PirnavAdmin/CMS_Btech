function freeze(value) {
  if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value) }
  return value
}
export const MODULE_REGISTRY = freeze(entries)
export const MODULE_BY_ID = Object.freeze(Object.fromEntries(MODULE_REGISTRY.map(module => [module.id, module])))

// Descriptive route ownership, not an authorization or redirect function.
export function findModuleForPath(pathname) {
  if (typeof pathname !== 'string' || !pathname.startsWith('/')) return null
  const path = pathname.split(/[?#]/)[0].replace(/\/$/, '') || '/'
  return MODULE_REGISTRY.flatMap(module => [module.path, ...module.aliases].map(prefix => ({ module, prefix })))
    .filter(({ prefix }) => path === prefix || (prefix !== '/' && path.startsWith(prefix + '/')))
    .sort((a, b) => b.prefix.length - a.prefix.length)[0]?.module || null
}
