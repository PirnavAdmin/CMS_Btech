test('role creation and editing use distinct supported mutations', async () => {
  roleApi.create.mockResolvedValue({ roleId: 41 })
  roleApi.update.mockResolvedValue({ id: 41 })
  render(<RolesAndDesignations />)
  await screen.findByText(/No.*roles/i)
  fireEvent.click(screen.getByRole('button', { name: 'Create New Role' }))
  let dialog = screen.getByRole('dialog', { name: 'Access Role' })
  fireEvent.change(within(dialog).getByLabelText('Role Name'), { target: { value: 'Academic Reviewer' } })
  fireEvent.change(within(dialog).getByLabelText('Role Category'), { target: { value: 'Academic' } })
  fireEvent.change(within(dialog).getByLabelText('Role Hierarchy Level'), { target: { value: 'Level 4 (Academic Staff)' } })
  fireEvent.submit(dialog.querySelector('form'))
  await waitFor(() => expect(roleApi.create).toHaveBeenCalledOnce())
  await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
  expect(roleApi.create.mock.calls[0][0]).toMatchObject({ name: 'Academic Reviewer', code: 'ACADEMIC_REVIEWER' })
  fireEvent.click(screen.getByRole('button', { name: /Edit Role Details/i }))
  dialog = screen.getByRole('dialog', { name: 'Access Role' })
  fireEvent.change(within(dialog).getByLabelText('Role Name'), { target: { value: 'Senior Academic Reviewer' } })
  fireEvent.submit(dialog.querySelector('form'))
  await waitFor(() => expect(roleApi.update).toHaveBeenCalledWith('41', expect.objectContaining({ name: 'Senior Academic Reviewer' })))
  expect(roleApi.create).toHaveBeenCalledOnce()
})

